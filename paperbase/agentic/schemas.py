def transport_projection_model(projection_type: str):
    """Wrap the existing production payloads without copying semantic fields."""
    from pydantic import create_model

    def payload_model(model):
        # Runtime identity belongs to the outer transport item. Derive every
        # semantic field from the production model; never maintain a second
        # support/status contract. Local validation rebinds this identity.
        return create_model(
            f"{model.__name__}TransportPayload",
            __config__=model.model_config,
            **{name: (field.annotation, field)
               for name, field in model.model_fields.items() if name != "evidence_id"},
        )

    payload_type = {
        "enumeration": EnumerationProjectionDraft,
        "comparison": ComparisonProjectionDraft,
        "mechanism": MechanismProjectionDraft,
    }.get(projection_type)
    if projection_type in {"fact", "mechanism"}:
        qualified, irrelevant = (
            (QualifiedFactProjectionDraft, IrrelevantFactProjectionDraft)
            if projection_type == "fact"
            else (QualifiedMechanismProjectionDraft, IrrelevantMechanismProjectionDraft)
        )
        payload_type = Annotated[
            payload_model(qualified) | payload_model(irrelevant),
            Field(discriminator="status"),
        ]
    else:
        payload_type = payload_model(payload_type)
    item = create_model(
        f"{projection_type.title()}TransportItem",
        __config__=ConfigDict(extra="forbid", strict=True),
        evidence_id=(NonEmptyText, ...),
        projections=(list[payload_type], Field(max_length=8 if projection_type == "fact" else 1)),
    )
    return create_model(
        f"{projection_type.title()}TransportBatch",
        __config__=ConfigDict(extra="forbid", strict=True),
        items=(list[item], Field(min_length=1, max_length=32)),
    )
